export function getBrandModels(brand) {
  const match = PHONE_CATALOG.find(item => item.brand.toLowerCase() === String(brand || '').toLowerCase());
  return match?.models || [];
}

export function searchPhoneModels(query, selectedBrand = '') {
  const q = String(query || '').trim().toLowerCase();
  const tokens = q.split(/\s+/).filter(Boolean);
  const knownBrand = PHONE_CATALOG.some(item => item.brand.toLowerCase() === String(selectedBrand || '').toLowerCase());
  const scoped = selectedBrand && knownBrand
    ? PHONE_CATALOG.filter(item => item.brand.toLowerCase() === selectedBrand.toLowerCase())
    : PHONE_CATALOG;

  const rows = [];
  for (const item of scoped) {
    for (const model of item.models) {
      const haystack = `${item.brand} ${item.aliases.join(' ')} ${model}`.toLowerCase();
      if (!q || tokens.every(token => haystack.includes(token))) rows.push({ brand: item.brand, model });
    }
  }

  if (!q && selectedBrand) return rows.slice(0, 40);
  return rows.slice(0, 80);
}
